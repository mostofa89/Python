num1 = 10
num2 = 20
difference = num2 - num1
print("The difference is:", difference)  # Output: The difference is: 10

num3 = 15.5
num4 = 4.5
difference_float = num3 - num4
print("The difference of floats is:", difference_float)  # Output: The difference of floats is: 11.0

