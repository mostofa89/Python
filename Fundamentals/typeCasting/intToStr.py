num1 = 940746
num2 = -28907

str_num1 = str(num1)
str_num2 = str(num2)

print(str_num1)  # Output: "940746"
print(str_num2)  # Output: "-28907"
print(type(str_num1))  # Output: <class 'str'>
print(type(str_num2))  # Output: <class 'str'>
print(num1)  # Output: 940746
print(num2)  # Output: -28907
print(type(num1))  # Output: <class 'int'>
print(type(num2))  # Output: <class 'int'>
# Converting integer numbers to their string representations