str_num1 = "1.0"
str_num2 = "2.5"

float_num1 = float(str_num1)
float_num2 = float(str_num2)
result = float_num1 + float_num2

print(result)  # Output: 3.5
print(type(result))  # Output: <class 'float'>
print(float_num1)  # Output: 1.0
print(float_num2)  # Output: 2.5
print(type(float_num1))  # Output: <class 'float'>
print(type(float_num2))  # Output: <class 'float'>
# Converting string representations of floating-point numbers to actual float types