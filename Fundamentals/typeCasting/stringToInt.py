str1 = '100'
int1 = int(str1)
print(f"Type of str1: {type(str1)}")  # Output: <class 'str'>
print(f"Type of int1: {type(int1)}")  # Output: <class 'int'>
print(f"Value of str1: {str1}")        # Output: "100"
print(f"Value of int1: {int1}")        # Output: 100
print(f"Sum of int1 and 50: {int1 + 50}")  # Output: 150