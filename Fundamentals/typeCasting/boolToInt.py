flag = True
is_valid  = False

num1 = int(flag)
num2 = int(is_valid)

print(num1)  # Output: 1
print(num2)  # Output: 0
print(type(num1))  # Output: <class 'int'>
print(type(num2))  # Output: <class 'int'>
print(flag)  # Output: True
print(is_valid)  # Output: False
print(type(flag))  # Output: <class 'bool'>
print(type(is_valid))  # Output: <class 'bool'>
