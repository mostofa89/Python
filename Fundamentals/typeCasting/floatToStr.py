num1 = 1.0
num2 = 28907.082907

str_num1 = str(num1)
str_num2 = str(num2)

print(str_num1)  # Output: "1.0"
print(str_num2)  # Output: "28907.082907"
print(type(str_num1))  # Output: <class 'str'>
print(type(str_num2))  # Output: <class 'str'>
print(num1)  # Output: 1.0
print(num2)  # Output: 28907.082907
print(type(num1))  # Output: <class 'float'>
print(type(num2))  # Output: <class 'float'>
# Converting float numbers to their string representations