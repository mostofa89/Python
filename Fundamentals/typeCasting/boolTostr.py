flag = True
is_valid = True

print(str(flag))      # Output: 'True'
print(str(is_valid))  # Output: 'True'
print(type(str(flag)))      # Output: <class 'str'>
print(type(str(is_valid)))  # Output: <class 'str'>
print(flag)           # Output: True
print(is_valid)      # Output: True
print(type(flag))           # Output: <class 'bool'>
print(type(is_valid))      # Output: <class 'bool'>
# Converting boolean values to their string representations