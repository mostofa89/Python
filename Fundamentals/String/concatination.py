str1 = "Hello"
str2 = "World"

# Using + operator
result1 = str1 + " " + str2
print("Using + operator:", result1)

# Using join() method
result2 = " ".join([str1, str2])
print("Using join() method:", result2)

# Using format() method
result5 = "{} {}".format(str1, str2)
print("Using format() method:", result5)

